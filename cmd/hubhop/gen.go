// gen turns the HubHop database into draft aircraft profiles.
//
// Only the variables it can read with confidence become bindings: the preset
// has to be readable, its code has to be a single variable with at most a
// simple arithmetic or comparison tail, and its label has to match one of the
// rules below. Everything else is left alone — the adapter's own reading is
// already right for most aircraft, and a wrong override is worse than none.
func gen(args []string) {
	fset := flag.NewFlagSet("gen", flag.ExitOnError)
	sim := fset.String("sim", "msfs", "simulator database: msfs or xplane")
	out := fset.String("out", "internal/profiles/builtin", "directory to write profiles into")
	minPoints := fset.Int("min-points", 1, "skip aircraft with fewer mapped data points than this")
	dry := fset.Bool("dry-run", false, "print what would be written without writing it")
	fset.Parse(flagsFirst(args))

	presets, err := fetch(*sim)
	exitOn(err)

	simulator := "simconnect"
	if *sim != "msfs" {
		simulator = "xplane"
	}

	// Existing profiles are hand-written and win: a generated draft never
	// overwrites one, and never competes with one for the same aircraft.
	existing := map[string]bool{}
	if entries, err := os.ReadDir(*out); err == nil {
		for _, e := range entries {
			if !strings.HasSuffix(e.Name(), ".json") {
				continue
			}
			body, err := os.ReadFile(filepath.Join(*out, e.Name()))
			if err != nil {
				continue
			}
			var doc struct {
				ID        string `json:"id"`
				Generated bool   `json:"x-generated"`
			}
			if json.Unmarshal(body, &doc) == nil && doc.ID != "" && !doc.Generated {
				// Only profiles a person owns are protected. A draft still
				// carrying the x-generated marker is refreshed in place;
				// deleting the marker adopts it and freezes it.
				existing[doc.ID] = true
			}
		}
	}

	groups := map[string][]preset{}
	for _, p := range presets {
		if !strings.Contains(p.PresetType, "Output") {
			continue
		}
		if skipVendor(p.Vendor) || strings.EqualFold(p.Aircraft, "Generic") {
			continue
		}
		key := p.Vendor + "\x00" + p.Aircraft
		groups[key] = append(groups[key], p)
	}

	keys := make([]string, 0, len(groups))
	for k := range groups {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	written, skipped := 0, 0
	for _, key := range keys {
		parts := strings.SplitN(key, "\x00", 2)
		vendor, aircraft := parts[0], parts[1]

		id := profileID(vendor, aircraft)
		if existing[id] || handWritten.MatchString(vendor+" "+aircraft) {
			skipped++
			continue
		}

		mash := buildMash(groups[key], simulator)
		if len(mash) < *minPoints {
			continue
		}

		sel, ok := selector(vendor, aircraft, simulator)
		if !ok {
			continue
		}
		doc := map[string]any{
			"id":          id,
			"name":        strings.TrimSpace(vendor + " " + cleanModel(aircraft)),
			"description": fmt.Sprintf("%s. Reads the data points below from the aircraft's own variables instead of the stock ones.", strings.TrimSpace(vendor+" "+cleanModel(aircraft))),
			"notes": "Generated by `go run ./cmd/hubhop gen` from the MobiFlight HubHop community " +
				"database. The selector and the bindings have not been confirmed in the simulator: " +
				"treat this as a starting point, and correct it in place once flown. Every binding " +
				"falls back to the stock variable, so an unread aircraft variable costs nothing.",
			"x-generated": true,
			"priority":    50,
			"match":       sel,
			"mash":        mash,
		}

		path := filepath.Join(*out, id+".json")
		if *dry {
			fmt.Printf("%-34s %-44s %d point(s)\n", id, vendor+" "+aircraft, len(mash))
			continue
		}
		body, err := json.MarshalIndent(doc, "", "  ")
		exitOn(err)
		exitOn(os.WriteFile(path, append(body, '\n'), 0o644))
		written++
		fmt.Printf("%-34s %-44s %d point(s)\n", id, vendor+" "+aircraft, len(mash))
	}
	fmt.Fprintf(os.Stderr, "\n%d profile(s) written, %d aircraft already covered by a hand-written profile\n", written, skipped)
}

// skipVendor drops the entries that are not a specific add-on aircraft.
func skipVendor(vendor string) bool {
	switch strings.ToLower(strings.TrimSpace(vendor)) {
	case "", "microsoft", "asobo", "unknown", "generic":
		return true
	}
	return false
}

// --- code parsing -----------------------------------------------------------

// simpleCode is a HubHop code reduced to one variable plus a transform this
// project can express. Anything with branching, several variables or an
// operator outside the set below is rejected rather than guessed at.
type simpleCode struct {
	kind  string // lvar, simvar or dataref
	name  string
	unit  string
	steps []map[string]any
}

var (
	varRe  = regexp.MustCompile(`^\(\s*([LAK]):([^,)]+?)\s*(?:,\s*([^)]*?)\s*)?\)`)
	drefRe = regexp.MustCompile(`^([A-Za-z0-9_]+(?:/[A-Za-z0-9_\-.]+)+(?:\[\d+\])?)$`)
	numRe  = regexp.MustCompile(`^-?\d+(?:\.\d+)?$`)
)

var opNames = map[string]string{
	">": "gt", "<": "lt", ">=": "gte", "<=": "lte", "==": "eq", "!=": "ne",
	"*": "scale", "/": "divide", "+": "offset",
}

func parseCode(code, simulator string) (simpleCode, bool) {
	code = strings.TrimSpace(code)

	if simulator == "xplane" {
		if drefRe.MatchString(code) {
			return simpleCode{kind: "dataref", name: code}, true
		}
		return simpleCode{}, false
	}

	m := varRe.FindStringSubmatch(code)
	if m == nil {
		return simpleCode{}, false
	}
	kind := map[string]string{"L": "lvar", "A": "simvar"}[m[1]]
	if kind == "" {
		return simpleCode{}, false // K: is an event, not readable
	}

	sc := simpleCode{kind: kind, name: strings.TrimSpace(m[2])}
	if kind == "simvar" {
		sc.unit = strings.TrimSpace(m[3])
	}
	if sc.name == "" || strings.ContainsAny(sc.name, "()>< ") && kind == "lvar" {
		return simpleCode{}, false
	}

	// The tail must be a flat sequence of "<number> <operator>" pairs or "!".
	rest := strings.Fields(strings.TrimSpace(code[len(m[0]):]))
	for i := 0; i < len(rest); i++ {
		if rest[i] == "!" {
			sc.steps = append(sc.steps, map[string]any{"op": "not"})
			continue
		}
		if !numRe.MatchString(rest[i]) || i+1 >= len(rest) {
			return simpleCode{}, false
		}
		value, err := strconv.ParseFloat(rest[i], 64)
		if err != nil {
			return simpleCode{}, false
		}
		op, ok := opNames[rest[i+1]]
		if !ok {
			return simpleCode{}, false
		}
		if op == "divide" && value == 0 {
			return simpleCode{}, false
		}
		sc.steps = append(sc.steps, map[string]any{"op": op, "value": value})
		i++
	}
	return sc, true
}

// aircraftSpecific reports whether the code reads something the add-on adds,
// rather than a variable the adapter already collects by default.
func (s simpleCode) aircraftSpecific(simulator string) bool {
	if simulator == "xplane" {
		return !strings.HasPrefix(s.name, "sim/")
	}
	return s.kind == "lvar"
}

func (s simpleCode) yieldsBool() bool {
	for _, st := range s.steps {
		switch st["op"] {
		case "gt", "lt", "gte", "lte", "eq", "ne", "not":
			return true
		}
	}
	return false
}

func (s simpleCode) binding(simulator string, extra []map[string]any) map[string]any {
	src := map[string]any{"kind": s.kind, "name": s.name}
	if s.unit != "" {
		src["unit"] = s.unit
	}
	b := map[string]any{"sim": simulator, "source": src}
	if steps := append(append([]map[string]any{}, s.steps...), extra...); len(steps) > 0 {
		b["transform"] = steps
	}
	return b
}

// --- data point rules -------------------------------------------------------

// rule maps HubHop labels onto one of the ACARS data points. Matching is
// deliberately narrow: the label has to name the concept AND, for the boolean
// points, look like an indication rather than a command.
type rule struct {
	point string
	// want and not are matched against the preset's label and description.
	want *regexp.Regexp
	not  *regexp.Regexp
	// name is matched against the variable's own name. A label can describe
	// anything; requiring the variable to be named for the concept as well is
	// what stops an "AP ALT light" from being read as "autopilot engaged".
	name     *regexp.Regexp
	reduce   string // or / and / "" for first-usable-wins
	numeric  bool   // a value rather than a lamp: take the single best candidate
	fallback map[string]simpleCode
}

func re(pattern string) *regexp.Regexp { return regexp.MustCompile("(?i)" + pattern) }

// lampNameRe matches a variable named for an indication rather than a value.
// Underscores and slashes are the separators these names actually use, which
// a word boundary does not see.
var lampNameRe = re(`(^|[_/])(ann|annun|led|light|lt|lamp|button|btn|switch|sw|dashed|` +
	`managed|dot|source|digits|status|mode|arm|armed)([_/0-9]|$)`)

func sv(name, unit string) simpleCode { return simpleCode{kind: "simvar", name: name, unit: unit} }
func dref(name string) simpleCode     { return simpleCode{kind: "dataref", name: name} }

