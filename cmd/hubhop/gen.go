// buildMash turns one aircraft's presets into the mash section of a profile.
func buildMash(presets []preset, simulator string) map[string]any {
	mash := map[string]any{}

	for _, r := range rules {
		var candidates []simpleCode
		seen := map[string]bool{}

		for _, p := range presets {
			text := p.Label + " " + p.Description
			if !r.want.MatchString(text) || (r.not != nil && r.not.MatchString(text)) {
				continue
			}
			sc, ok := parseCode(p.Code, simulator)
			if !ok || seen[sc.name] {
				continue
			}
			// The variable has to be named for the concept, not merely
			// mentioned by a label that also names it.
			if r.name != nil && !r.name.MatchString(sc.name) {
				continue
			}
			// A generated profile only earns its place by binding something
			// the adapter does not already read. A stock simulation variable
			// or a stock X-Plane dataref is either a no-op or a mistake.
			if !sc.aircraftSpecific(simulator) {
				continue
			}
			// A value cannot come from a comparison, and a lamp is not a value —
			// "mcp_vs_dial_ann" reports the annunciator, not the selection.
			if r.numeric && (sc.yieldsBool() || lampNameRe.MatchString(sc.name)) {
				continue
			}
			seen[sc.name] = true
			candidates = append(candidates, sc)
		}
		if len(candidates) == 0 {
			continue
		}
		sort.Slice(candidates, func(i, j int) bool { return candidates[i].name < candidates[j].name })

		if r.numeric && len(candidates) > 1 {
			candidates = candidates[:1]
		}

		boolify := []map[string]any{{"op": "bool"}}
		var bindings []map[string]any
		for _, sc := range candidates {
			extra := []map[string]any(nil)
			if !r.numeric && !sc.yieldsBool() {
				extra = boolify
			}
			bindings = append(bindings, sc.binding(simulator, extra))
		}
		if fb, ok := r.fallback[simulator]; ok {
			extra := []map[string]any(nil)
			if !r.numeric {
				extra = boolify
			}
			bindings = append(bindings, fb.binding(simulator, extra))
		}

		if r.reduce != "" && len(bindings) > 1 {
			mash[r.point] = map[string]any{"reduce": r.reduce, "bindings": bindings}
		} else {
			mash[r.point] = bindings
		}
	}
	return mash
}

// --- naming and selectors ---------------------------------------------------

// handWritten matches the aircraft a hand-written profile already covers.
// Those profiles were checked against the aircraft's own files, so a generated
// draft must not compete with one.
var handWritten = re(`fenixsim|flight sim labs|fly by wire.*a320|pmdg.*(b737|b777)|` +
	`inibuilds.*(a350|a300|a310)|tfdi|aerosoft.*crj|ifly|just flight.*(bae|avro)|` +
	`leonardo|salty|zibo`)

// vendorPatterns maps a HubHop vendor onto the way its name actually appears
// in an aircraft title. An empty pattern means the vendor is not distinctive
// enough to put in a selector and the model has to carry it alone.
var vendorPatterns = map[string]string{
	"fly by wire":            `flybywire|fbw|a32nx`,
	"flight sim labs":        `fs\s*-?labs?`,
	"inibuilds":              `ini\s*-?builds?|inisim`,
	"just flight":            `just\s*-?flight`,
	"black square":           `black\s*-?square`,
	"a2a sim":                `a2a`,
	"hype performance group": `hype|hpg`,
	"flightsim studio (fss)": `fss|flightsim studio`,
	"dc designs":             `dc\s*-?designs`,
	"flight factor":          `flight\s*-?factor|ff`,
	"x-crafts":               `x\s*-?crafts`,
	"laminar research":       ``,
	"toliss":                 `toliss`,
	"ixeg":                   `ixeg`,
	"felis":                  `felis`,
}

var (
	parenRe    = regexp.MustCompile(`\s*\([^)]*\)`)
	suffixRe   = regexp.MustCompile(`(?i)\s*-\s*(sdk|dev|beta|wip)\b`)
	nonAlnumRe = regexp.MustCompile(`[^A-Za-z0-9]+`)
)

// cleanModel strips the bookkeeping HubHop carries in the aircraft name.
func cleanModel(aircraft string) string {
	return strings.TrimSpace(suffixRe.ReplaceAllString(parenRe.ReplaceAllString(aircraft, ""), ""))
}

// vendorIDs shorten the vendor half of a generated profile id.
var vendorIDs = map[string]string{
	"fly by wire":            "fbw",
	"flight sim labs":        "fslabs",
	"flightsim studio (fss)": "fss",
	"flight factor":          "flightfactor",
	"just flight":            "justflight",
	"black square":           "blacksquare",
	"hype performance group": "hpg",
	"dc designs":             "dcdesigns",
	"a2a sim":                "a2a",
	"headwind simulations":   "headwind",
	"miltech simulations":    "miltech",
	"x-crafts":               "xcrafts",
	"laminar research":       "laminar",
}

// profileID builds a stable, file-safe id from the vendor and the model.
func profileID(vendor, aircraft string) string {
	slug := func(s string) string {
		return strings.Trim(strings.ToLower(nonAlnumRe.ReplaceAllString(s, "-")), "-")
	}
	v, ok := vendorIDs[strings.ToLower(strings.TrimSpace(vendor))]
	if !ok {
		v = slug(vendor)
	}
	m := slug(cleanModel(aircraft))
	if m == "" {
		return v
	}
	return v + "-" + m
}

// tokenRe splits a model name into its letter and digit runs.
var (
	tokenRe    = regexp.MustCompile(`[A-Za-z]+|\d+`)
	wildcardRe = re(`x{2,}`)
)

// modelPattern turns a model name into a regular expression that tolerates the
// spacing and hyphens liveries vary on: "A340-600" and "A340 600" both match
// `a[\s-]*340`. It reports false for a family placeholder such as "E1XX",
// which names no aircraft a title would ever carry.
func modelPattern(model string) (string, bool) {
	if model == "" || wildcardRe.MatchString(model) {
		return "", false
	}
	tokens := tokenRe.FindAllString(strings.ToLower(model), -1)
	if len(tokens) == 0 {
		return "", false
	}

	// Prefer "<short letter prefix><number>", the way airframes are named.
	for i, tok := range tokens {
		if len(tok) < 2 || tok[0] < '0' || tok[0] > '9' {
			continue
		}
		if i > 0 && len(tokens[i-1]) <= 3 && tokens[i-1][0] >= 'a' {
			return regexp.QuoteMeta(tokens[i-1]) + `[\s-]*` + tok, true
		}
		return tok, true
	}

	// No model number: fall back to the words themselves ("Concorde", "Duke").
	words := make([]string, 0, len(tokens))
	for _, tok := range tokens {
		if len(tok) >= 3 {
			words = append(words, regexp.QuoteMeta(tok))
		}
	}
	if len(words) == 0 {
		return "", false
	}
	return strings.Join(words, `[\s-]*`), true
}

// selector builds the match expression: the simulator, the vendor as it shows
// up in a title where that is distinctive, and the model number with the
// spacing and hyphens liveries vary on. It reports false when the aircraft
// name carries nothing specific enough to match on.
func selector(vendor, aircraft, simulator string) (map[string]any, bool) {
	conds := []map[string]any{
		{"field": "simulator", "op": "equals", "value": simulator},
	}

	if pattern, ok := vendorPatterns[strings.ToLower(strings.TrimSpace(vendor))]; ok {
		if pattern != "" {
			conds = append(conds, map[string]any{"field": "aircraftName", "op": "matches", "value": pattern})
		}
	} else if v := strings.TrimSpace(vendor); v != "" {
		conds = append(conds, map[string]any{
			"field": "aircraftName", "op": "matches",
			"value": regexp.QuoteMeta(strings.ToLower(strings.Fields(v)[0])),
		})
	}

	pattern, ok := modelPattern(cleanModel(aircraft))
	if !ok {
		return nil, false
	}
	conds = append(conds, map[string]any{"field": "aircraftName", "op": "matches", "value": pattern})

	if len(conds) < 3 {
		return nil, false // the simulator plus one clause is too loose to ship
	}
	return map[string]any{"all": conds}, true
}
