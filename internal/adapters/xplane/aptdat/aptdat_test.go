// A malformed airport keeps what can be read; rows from the next airport
// never leak into it.
func TestAnAirportIsReadUpToTheNextOne(t *testing.T) {
	rec, err := parseAirport(strings.NewReader(egllRows + "100 short row\n" + egwuRows))
	if err != nil {
		t.Fatal(err)
	}
	if rec.ident != "EGLL" || rec.icao != "EGLL" || len(rec.runways) != 1 || len(rec.stands) != 2 {
		t.Fatalf("record = %+v", rec)
	}
	if _, err := parseAirport(strings.NewReader("99\n")); !errors.Is(err, errNotAnAirport) {
		t.Fatalf("end-of-file row read as an airport: %v", err)
	}
}

func TestCIFPRunwayRecordsAreRead(t *testing.T) {
	got := parseCIFPElevations(strings.NewReader(egllCIFP + "RWY:RW18,  ,  ,-0012,\nRWY:RWX,1,2,abc,\n"))
	want := map[string]float64{"09L": 79, "27R": 78, "18": -12}
	if len(got) != len(want) {
		t.Fatalf("elevations = %v, want %v", got, want)
	}
	for k, v := range want {
		if got[k] != v {
			t.Errorf("%s = %v, want %v", k, got[k], v)
		}
	}
}

// The ident becomes a file name, so it must be one and nothing more.
func TestOnlyAirportIdentsNameCIFPFiles(t *testing.T) {
	for _, bad := range []string{"", "../EGLL", `..\x`, "EG LL", "egll", "TOOLONGID"} {
		if validIdent(bad) {
			t.Errorf("%q accepted as an airport ident", bad)
		}
	}
	for _, ok := range []string{"EGLL", "KJFK", "X1", "SBGR"} {
		if !validIdent(ok) {
			t.Errorf("%q rejected as an airport ident", ok)
		}
	}
}
