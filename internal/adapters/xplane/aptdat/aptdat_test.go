// xplaneRoot builds an X-Plane folder holding the given files.
func xplaneRoot(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	for rel, body := range files {
		p := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

const globalPath = "Global Scenery/Global Airports/Earth nav data/apt.dat"

func sourceAt(root string) *Source {
	s := NewSource(func() string { return root })
	s.findRunning = func() (string, bool) { return "", false }
	return s
}

// atStandA12 is an aircraft parked on Heathrow's stand A12.
const atA12Lat, atA12Lon = 51.47121, -0.45981

// The whole path: the index is built from the global airports, the airport
// the aircraft is at is read back, and its runway ends get their own
// elevations from the navdata.
func TestAnAirportIsReadFromTheGlobalAirports(t *testing.T) {
	root := xplaneRoot(t, map[string]string{
		globalPath:                             globalAptDat,
		"Resources/default data/CIFP/EGLL.dat": egllCIFP,
	})
	l, err := sourceAt(root).NearestAirportLayout(context.Background(), atA12Lat, atA12Lon)
	if err != nil {
		t.Fatal(err)
	}
	if l.ICAO != "EGLL" || len(l.Runways) != 1 {
		t.Fatalf("layout = %+v, want EGLL with one runway", l)
	}
	ends := l.Runways[0].Ends
	if ends[0].Designator != "09L" || ends[0].Lat != 51.4775 || ends[0].Lon != -0.484961 || ends[1].Designator != "27R" {
		t.Fatalf("runway ends = %+v", ends)
	}
	if ends[0].AltFt != 79 || ends[1].AltFt != 78 {
		t.Fatalf("end elevations = %.0f, %.0f ft; the CIFP gives 79 and 78", ends[0].AltFt, ends[1].AltFt)
	}
	names := []string{}
	for _, s := range l.Stands {
		names = append(names, s.Name)
	}
	if strings.Join(names, ",") != "A12,Remote Stand 5" {
		t.Fatalf("stands = %v, want A12 and Remote Stand 5 (the broken row skipped)", names)
	}
	if l.RefLat != 51.4775 || l.RefLon != -0.461389 {
		t.Fatalf("reference = %v,%v, want the datum", l.RefLat, l.RefLon)
	}
}

// The pilot's AIRAC cycle in Custom Data wins over the navdata X-Plane
// ships; without either, the ends keep the airport elevation.
func TestRunwayElevationsComeFromTheNewestNavdata(t *testing.T) {
	airac := strings.ReplaceAll(egllCIFP, "00079", "00081")
	root := xplaneRoot(t, map[string]string{
		globalPath:                             globalAptDat,
		"Custom Data/CIFP/EGLL.dat":            airac,
		"Resources/default data/CIFP/EGLL.dat": egllCIFP,
	})
	l, err := sourceAt(root).NearestAirportLayout(context.Background(), atA12Lat, atA12Lon)
	if err != nil {
		t.Fatal(err)
	}
	if got := l.Runways[0].Ends[0].AltFt; got != 81 {
		t.Fatalf("09L elevation = %.0f ft, want the AIRAC's 81", got)
	}

	bare := xplaneRoot(t, map[string]string{globalPath: globalAptDat})
	l, err = sourceAt(bare).NearestAirportLayout(context.Background(), atA12Lat, atA12Lon)
	if err != nil {
		t.Fatal(err)
	}
	if got := l.Runways[0].Ends[0].AltFt; got != 83 {
		t.Fatalf("09L elevation without navdata = %.0f ft, want the airport's 83", got)
	}
}

// A custom scenery pack replaces the global version of its airport, as it
// does in the simulator.
func TestCustomSceneryWinsOverTheGlobalAirports(t *testing.T) {
	root := xplaneRoot(t, map[string]string{
		globalPath: globalAptDat,
		"Custom Scenery/Payware EGLL/Earth nav data/apt.dat": customEGLL,
		"Custom Scenery/scenery_packs.ini": "I\n1000 Version\nSCENERY\n\n" +
			"SCENERY_PACK Custom Scenery/Payware EGLL/\n" +
			"SCENERY_PACK *GLOBAL_AIRPORTS*\n",
	})
	l, err := sourceAt(root).NearestAirportLayout(context.Background(), atA12Lat, atA12Lon)
	if err != nil {
		t.Fatal(err)
	}
	if len(l.Stands) != 1 || l.Stands[0].Name != "412" {
		t.Fatalf("stands = %+v, want the payware's stand 412", l.Stands)
	}
}

func TestSceneryPacksAreReadInTheSimulatorsOrder(t *testing.T) {
	pack := func(name string) string { return "Custom Scenery/" + name + "/Earth nav data/apt.dat" }
	root := xplaneRoot(t, map[string]string{
		globalPath:        "I\n99\n",
		pack("First"):     "I\n99\n",
		pack("Disabled"):  "I\n99\n",
		pack("Last"):      "I\n99\n",
		pack("NotListed"): "I\n99\n",
		"Custom Scenery/scenery_packs.ini": "I\n1000 Version\nSCENERY\n\n" +
			"SCENERY_PACK Custom Scenery/First/\n" +
			"SCENERY_PACK_DISABLED Custom Scenery/Disabled/\n" +
			"SCENERY_PACK *GLOBAL_AIRPORTS*\n" +
			"SCENERY_PACK Custom Scenery/Last/\r\n" +
			"SCENERY_PACK Custom Scenery/Missing/\n",
	})
	var got []string
	for _, f := range sceneryFiles(root) {
		rel, _ := filepath.Rel(root, f)
		got = append(got, filepath.ToSlash(rel))
	}
	want := []string{pack("First"), globalPath, pack("Last")}
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Fatalf("apt.dat order = %v\nwant %v", got, want)
	}

	// X-Plane 11 has no *GLOBAL_AIRPORTS* line: the global airports come last.
	xp11 := xplaneRoot(t, map[string]string{
		"Resources/default scenery/default apt dat/Earth nav data/apt.dat": "I\n99\n",
		pack("Mine"):                       "I\n99\n",
		"Custom Scenery/scenery_packs.ini": "SCENERY_PACK Custom Scenery/Mine/\n",
	})
	files := sceneryFiles(xp11)
	if len(files) != 2 || !strings.Contains(filepath.ToSlash(files[1]), "default apt dat") {
		t.Fatalf("X-Plane 11 order = %v, want the pack then the default airports", files)
	}
}

// The airport chosen is the one the aircraft is on, and none at sea.
func TestTheAirportUnderTheAircraftIsChosen(t *testing.T) {
	root := xplaneRoot(t, map[string]string{globalPath: globalAptDat})
	s := sourceAt(root)

	l, err := s.NearestAirportLayout(context.Background(), 51.552, -0.415)
	if err != nil || l.ICAO != "EGWU" {
		t.Fatalf("on Northolt's runway got %+v, %v", l, err)
	}
	if _, err := s.NearestAirportLayout(context.Background(), 50.0, -20.0); !errors.Is(err, domain.ErrNoAirportData) {
		t.Fatalf("mid-Atlantic: err = %v, want ErrNoAirportData", err)
	}
}

// Without an X-Plane folder there is nothing to read, which is not a fault.
func TestNoXPlaneFolderIsNoAirportData(t *testing.T) {
	s := sourceAt("")
	if _, err := s.NearestAirportLayout(context.Background(), atA12Lat, atA12Lon); !errors.Is(err, domain.ErrNoAirportData) {
		t.Fatalf("err = %v, want ErrNoAirportData", err)
	}
	empty := sourceAt(t.TempDir())
	if _, err := empty.NearestAirportLayout(context.Background(), atA12Lat, atA12Lon); !errors.Is(err, domain.ErrNoAirportData) {
		t.Fatalf("folder without apt.dat: err = %v, want ErrNoAirportData", err)
	}
}

